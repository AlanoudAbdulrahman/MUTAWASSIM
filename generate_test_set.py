def generate_test_set(output_file="test_set.json"):
    data = []
    
    for text in fabricated_weak:
        # خلط بين موضوع وضعيف عشوائيا
        status = random.choice(["fabricated", "weak"])
        data.append({"claim_text": text, "expected_status": status})
        
    for text in confirmed:
        data.append({"claim_text": text, "expected_status": "confirmed"})
        
    for text in needs_review:
        data.append({"claim_text": text, "expected_status": "needs_review"})
        
    # خلط البيانات لكي لا تكون مرتبة
    random.shuffle(data)
    
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        
    print(f"Generated {len(data)} test cases in {output_file}")

if __name__ == "__main__":
    generate_test_set()
